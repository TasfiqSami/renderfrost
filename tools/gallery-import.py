#!/usr/bin/env python3
"""
Turn raw screenshots into web-ready gallery images.

Drop originals in  assets/img/gallery/_raw/<Credit name>/*.png|jpg
then run:  python3 tools/gallery-import.py   (needs Pillow)

It writes a 1600px WebP and a 640px WebP thumbnail per picture, rewrites
assets/img/gallery/gallery.json and leaves the originals untouched.
"""
import json, os, re, sys, datetime
from multiprocessing import Pool
from PIL import Image, ImageStat, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAL = os.path.join(ROOT, "assets", "img", "gallery")
RAW = os.path.join(GAL, "_raw")
EXT = (".png", ".jpg", ".jpeg", ".webp")

def slug(s): return re.sub(r"[^A-Za-z0-9_-]+", "-", s).strip("-")

def taken(name):
    m = re.search(r"(20\d\d)-(\d\d)-(\d\d)", name)
    if m:
        try: return datetime.date(int(m[1]), int(m[2]), int(m[3])).isoformat()
        except ValueError: pass
    m = re.match(r"(\d{17,20})_", name)           # Discord message id -> upload date
    if m:
        ts = (int(m[1]) >> 22) + 1420070400000
        return datetime.datetime.fromtimestamp(ts / 1000, datetime.timezone.utc).date().isoformat()
    return ""

def work(job):
    src, credit, idx = job
    name = os.path.basename(src)
    stem = slug(os.path.splitext(name)[0])[:60]
    out_dir = os.path.join(GAL, slug(credit))
    os.makedirs(out_dir, exist_ok=True)
    full, thumb = f"{stem}.webp", f"{stem}-t.webp"
    im = Image.open(src).convert("RGB")
    ow, oh = im.size
    a = im.copy(); a.thumbnail((1600, 1600), Image.LANCZOS)
    a.save(os.path.join(out_dir, full), "WEBP", quality=80, method=6)
    t = im.copy(); t.thumbnail((640, 640), Image.LANCZOS)
    t.save(os.path.join(out_dir, thumb), "WEBP", quality=74, method=6)
    # "interesting" score: colourfulness + detail, used to pick highlights
    s = t.resize((160, 90)); st = ImageStat.Stat(s)
    color = sum(st.stddev) / 3
    detail = ImageStat.Stat(s.convert("L").filter(ImageFilter.FIND_EDGES)).mean[0]
    return {"file": f"{slug(credit)}/{full}", "thumb": f"{slug(credit)}/{thumb}", "credit": credit,
            "date": taken(name), "w": a.size[0], "h": a.size[1], "score": round(color + detail * 2, 1)}

def main():
    jobs = []
    for credit in sorted(os.listdir(RAW)):
        d = os.path.join(RAW, credit)
        if not os.path.isdir(d): continue
        for i, f in enumerate(sorted(os.listdir(d))):
            if f.lower().endswith(EXT): jobs.append((os.path.join(d, f), credit, i))
    with Pool() as p: items = p.map(work, jobs, chunksize=4)
    # keep hand-edited fields (caption, featured rank) from the previous run
    old = {}
    try:
        old = {e["file"]: e for e in json.load(open(os.path.join(GAL, "gallery.json"), encoding="utf8"))["images"]}
    except (OSError, ValueError, KeyError):
        pass
    for e in items:
        for k in ("caption", "featured"):
            if k in old.get(e["file"], {}): e[k] = old[e["file"]][k]
    items.sort(key=lambda e: (e["date"], e["file"]), reverse=True)
    with open(os.path.join(GAL, "gallery.json"), "w", encoding="utf8") as fh:
        json.dump({"_help": "Generated by tools/gallery-import.py. Edit 'caption' freely; give up to five pictures a 'featured' rank (1 = biggest tile).", "images": items}, fh, indent=1, ensure_ascii=False)
    print(len(items), "images processed")

if __name__ == "__main__":
    main()
